export function findReading(surface, baseForm) {
  if (READING_MAP.has(surface)) return READING_MAP.get(surface);
  if (baseForm && READING_MAP.has(baseForm)) return READING_MAP.get(baseForm);
  // Katakana words: the surface IS the reading
  if (/^[\u30A1-\u30F6ー]+$/.test(surface)) return surface;
  // Pure hiragana: already readable
  if (/^[\u3041-\u3096]+$/.test(surface)) return surface;
  return "";
}

export function findGlossZh(surface, baseForm) {
  if (BASE_GLOSSARY.has(surface)) {
    return BASE_GLOSSARY.get(surface);
  }
  if (baseForm && BASE_GLOSSARY.has(baseForm)) {
    return BASE_GLOSSARY.get(baseForm);
  }
  return "";
}

export function getGlossaryEntries() {
  return Array.from(BASE_GLOSSARY.entries());
}
